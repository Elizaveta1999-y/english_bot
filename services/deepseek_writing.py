import os
import logging
import re
import aiohttp
import asyncio

logger = logging.getLogger(__name__)

DEEPSEEK_API_KEY = os.getenv("DEEPSEEK_API_KEY")
if not DEEPSEEK_API_KEY:
    logger.error("DEEPSEEK_API_KEY not set in environment variables")
    raise ValueError("DEEPSEEK_API_KEY is required. Please set it in your environment.")

BASE_URL = "https://api.deepseek.com/v1"

REQUEST_TIMEOUT = 90
MAX_RETRIES = 5
RETRY_DELAYS = [2, 4, 8, 16]


async def check_writing(task_text: str, user_answer: str, level: str, keywords: list, task_type: str) -> tuple:
    """
    Проверяет письменный ответ через DeepSeek.
    При успехе: (feedback, score).
    При провале: (None, None) — вызывающий код сам показывает сообщение пользователю.
    """
    if task_type == "email":
        criteria = (
            "Оценивай по следующим критериям:\n"
            "1. Структура письма (приветствие, основная часть, прощание).\n"
            "2. Грамматика и времена.\n"
            "3. Лексика (использование ключевых слов, уместность).\n"
            "4. Объём (соответствие заданию)."
        )
    elif task_type == "essay":
        criteria = (
            "Оценивай по следующим критериям:\n"
            "1. Соответствие теме и аргументированность (есть ли примеры, объяснения).\n"
            "2. Обязательная структура: начало (вступление), основная часть (аргументы/примеры), конец (заключение).\n"
            "3. Грамматика и лексика (связки, разнообразие слов).\n"
            "4. Логика и убедительность."
        )
    elif task_type == "post":
        criteria = (
            "Оценивай по следующим критериям:\n"
            "1. Использование хэштегов и смайликов (уместно, не перебор).\n"
            "2. Соответствие формату поста (краткость, выразительность).\n"
            "3. Грамматика и лексика.\n"
            "4. Оригинальность и вовлекающий стиль."
        )
    elif task_type == "story":
        criteria = (
            "Оценивай по следующим критериям:\n"
            "1. Начинается ли с 'One day' или аналогичного вступления.\n"
            "2. Использованы ли ключевые слова из задания.\n"
            "3. Есть ли концовка (чем всё закончилось).\n"
            "4. Связность и логика повествования.\n"
            "5. Грамматика и лексика (разнообразие)."
        )
    else:
        criteria = "Оценивай общие критерии: грамматика, лексика, соответствие теме."

    if level == "beginner":
        strictness = "мягкий. Хвали за попытку, даже если есть ошибки. Не требуй сложных конструкций."
    elif level == "intermediate":
        strictness = "средний. Обращай внимание на структуру, время, артикли, но не будь слишком строг."
    else:
        strictness = "строгий. Разбирай все ошибки: грамматику, лексику, стиль. Требуй высокого уровня."

    prompt = (
        f"Ты – опытный преподаватель английского языка. Проверь письменный ответ на задание.\n"
        f"Тип задания: {task_type}. Уровень пользователя: {level}.\n"
        f"Твой стиль проверки: {strictness}\n\n"
        f"Задание: {task_text}\n"
        f"Ключевые слова (можно использовать): {', '.join(keywords)}\n\n"
        f"Ответ пользователя:\n{user_answer}\n\n"
        f"{criteria}\n\n"
        "Оцени ответ по плану. Отвечай на русском языке, обращайся к пользователю на 'ты'.\n"
    )

    # === БИНАРНЫЙ МАРКЕР ПЕРВОЙ СТРОКОЙ ===
    prompt += (
        "\n!!! САМОЕ ПЕРВОЕ, ЧТО ТЫ ДЕЛАЕШЬ !!!\n"
        "Первой строкой своего ответа напиши РОВНО одно слово без разметки и знаков препинания:\n"
        "  OFF_TOPIC  — если ответ СОВЕРШЕННО НЕ ПО ТЕМЕ (нет ни одного слова, идеи, примера, факта по теме задания)\n"
        "  ON_TOPIC   — во всех остальных случаях (ответ по теме или ЧАСТИЧНО по теме)\n"
        "При ЛЮБОМ сомнении выбирай ON_TOPIC.\n"
        "Со второй строки — сам фидбек.\n"
    )

    # === ОБЩИЕ ПРАВИЛА ФОРМАТА ===
    prompt += (
        "\nВАЖНО: обращайся к пользователю на 'ты'.\n"
        "Используй HTML-разметку.\n"
        "ФОРМАТ ОТВЕТА:\n"
        "- Каждый критерий оформляй так: <b>Название критерия:</b> текст\n"
        "- После каждого критерия — ПУСТАЯ СТРОКА.\n"
        "- Последним блоком идёт <b>Советы по улучшению:</b> — затем ОДИН <blockquote>...</blockquote>, "
        "внутри которого все советы пронумерованы (1., 2., 3.), каждый с новой строки. "
        "НЕ оформляй каждый совет отдельным <blockquote>. Все советы — внутри ОДНОГО <blockquote>.\n"
        "После закрывающего </blockquote> НЕ ставь точку, запятую или другой знак — сразу переходи к строке 'Оценка: X/5'.\n"
        "Максимум 3 совета.\n"
        "Похвала и смайлик — только если текст хороший (оценка 4–5). Один смайлик из набора: 👍🏻, 👏🏻, 🤩, 😉, "
        "только внутри предложения с похвалой, НЕ отдельно и НЕ в конце. Во всём ответе максимум один смайлик.\n"
        "Если текст не очень хорош — похвалу НЕ пиши, смайлик НЕ ставь.\n"
        "Не используй Markdown-разметку (звёздочки, `>`, `#`).\n"
        "Начинай ответ сразу с разбора, без приветствий.\n"
        "Не используй другие эмодзи.\n"
        "В конце: Оценка: X/5."
    )

    # === ЖЁСТКОЕ ОГРАНИЧЕНИЕ ДЛИНЫ ===
    prompt += (
        "\n\n=== ЖЁСТКОЕ ОГРАНИЧЕНИЕ ДЛИНЫ ФИДБЕКА ===\n"
        "Фидбек должен быть КОРОТКИМ и КОНКРЕТНЫМ. Соблюдай строго:\n"
        "- Каждый критерий — МАКСИМУМ 1–2 предложения. Только суть, без воды.\n"
        "- НЕ пересказывай задание (пользователь его видит перед собой).\n"
        "- НЕ пересказывай ответ пользователя целиком. Указывай только то, что важно для оценки.\n"
        "- НЕ повторяй одну и ту же мысль разными словами.\n"
        "- НЕ пиши общих рассуждений вроде 'для уровня expert ожидается Y', 'это важно, потому что...'.\n"
        "- Цитаты из ответа — МАКСИМУМ 2–3 слова в кавычках. Не цитируй целые фразы.\n"
        "- Если есть ошибка — покажи исправление кратко: «было → стало» (2–4 слова).\n"
        "- Общий фидбек БЕЗ блока советов — МАКСИМУМ 5–7 предложений на всё.\n"
        "- Советы — 3 штуки, каждый ОДНО короткое предложение.\n"
        "Цель: пользователь должен прочитать фидбек за 15–20 секунд и понять, что улучшить.\n"
        "=== КОНЕЦ ОГРАНИЧЕНИЯ ===\n"
    )

    # === ОСОБОЕ ПРАВИЛО OFF-TOPIC ===
    prompt += (
        "\n\n=== ОСОБОЕ ПРАВИЛО: ЕСЛИ OFF_TOPIC ===\n"
        "Это правило ПЕРЕОПРЕДЕЛЯЕТ всё, что написано выше, если оно применимо.\n"
        "\nКРИТЕРИЙ 'СОВЕРШЕННО НЕ ПО ТЕМЕ' — срабатывает ТОЛЬКО если ответ вообще никак не касается заданной темы: "
        "нет ни одного слова, идеи, примера, факта, связанного с темой задания.\n"
        "ЕСЛИ ЕСТЬ ХОТЬ МАЛЕЙШЕЕ СОВПАДЕНИЕ С ТЕМОЙ — это НЕ считается 'не по теме', делай ПОЛНЫЙ разбор.\n"
        "ПРИ ЛЮБОМ СОМНЕНИИ трактуй в пользу пользователя: считай, что ответ ПО ТЕМЕ.\n"
        "\nЕсли ты написал OFF_TOPIC первой строкой, то со второй строки напиши РОВНО ЭТО и НИЧЕГО БОЛЬШЕ:\n"
        "\n<b>Ваш ответ совершенно не соответствует теме.</b>\n"
        "\n<b>Советы:</b>\n"
        "<blockquote>1. Внимательно прочитай задание — о чём именно нужно писать.\n"
        "2. Продумай 2–3 предложения строго по теме.\n"
        "3. Начни ответ с главной мысли задания.</blockquote>\n"
        "\nВ конце: Оценка: 1/5.\n"
        "\nСТРОГО ЗАПРЕЩЕНО при OFF_TOPIC (не пиши НИЧЕГО из этого):\n"
        "- Любые критерии: 'Соответствие теме:', 'Грамматика:', 'Лексика:', 'Структура:', "
        "'Советы по улучшению:', 'Оригинальность:', 'Логика:'.\n"
        "- Разбор грамматических ошибок и примеры их исправления.\n"
        "- Анализ лексики, структуры, стиля.\n"
        "- Цитирование фраз пользователя.\n"
        "- Похвалу, смайлики, вступления вроде 'Твой текст...'.\n"
        "=== КОНЕЦ ОСОБОГО ПРАВИЛА ===\n"
    )

    url = f"{BASE_URL}/chat/completions"
    headers = {
        "Authorization": f"Bearer {DEEPSEEK_API_KEY}",
        "Content-Type": "application/json"
    }
    payload = {
        "model": "deepseek-chat",
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": 600,
        "temperature": 0.5
    }

    last_error = None

    for attempt in range(1, MAX_RETRIES + 1):
        try:
            timeout = aiohttp.ClientTimeout(total=REQUEST_TIMEOUT)
            async with aiohttp.ClientSession(timeout=timeout) as session:
                async with session.post(url, headers=headers, json=payload) as resp:
                    if resp.status != 200:
                        text = await resp.text()
                        raise Exception(f"HTTP {resp.status}: {text[:200]}")

                    data = await resp.json()
                    feedback = data["choices"][0]["message"]["content"]

            if not feedback or not feedback.strip():
                raise Exception("Пустой ответ от DeepSeek")

            # Чистим Markdown
            feedback = re.sub(r'#{1,6}', '', feedback)
            feedback = re.sub(r'`', '', feedback)

            # Извлекаем оценку
            score = 3
            match = re.search(r'Оценка:\s*(\d+)\s*[/]?\s*5', feedback)
            if match:
                score = int(match.group(1))
                if score < 1:
                    score = 1
                elif score > 5:
                    score = 5
                feedback = re.sub(r'Оценка:\s*\d+\s*[/]?\s*5', '', feedback).strip()

            # Убираем висячие точки/запятые/двоеточия в конце
            feedback = re.sub(r'[\s\.\,\;\:]+$', '', feedback).strip()

            return feedback, score

        except asyncio.TimeoutError:
            last_error = "timeout"
            logger.warning(f"Writing: таймаут DeepSeek (попытка {attempt}/{MAX_RETRIES})")
        except aiohttp.ClientError as e:
            last_error = f"client_error: {e}"
            logger.warning(f"Writing: ClientError (попытка {attempt}/{MAX_RETRIES}): {e}")
        except Exception as e:
            last_error = str(e)
            logger.warning(f"Writing: ошибка (попытка {attempt}/{MAX_RETRIES}): {e}")

        if attempt < MAX_RETRIES:
            delay = RETRY_DELAYS[attempt - 1] if attempt - 1 < len(RETRY_DELAYS) else RETRY_DELAYS[-1]
            await asyncio.sleep(delay)

    logger.error(f"Writing: все попытки исчерпаны. Последняя ошибка: {last_error}")
    return None, None